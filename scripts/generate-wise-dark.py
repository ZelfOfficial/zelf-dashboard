#!/usr/bin/env python3
"""
Generates src/styles/wise-dark.scss.

Light mode keeps the green-tinted Wise neutral ramp from tailwind.config.js (Fog -> Charcoal ->
Forest Ink -> Obsidian). In dark mode, the legacy `dark:*-gray-*` / slate / zinc utilities that the
templates use resolve to the inverted Wise palette instead: deep forest surfaces, Forest Ink cards,
Linen Mist text and hairlines. Only classes that actually appear in src/app are emitted.

Re-run after adding new dark: neutral utilities:  python3 scripts/generate-wise-dark.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SURFACE = {50: "#2a5e0c", 100: "#2a5e0c", 200: "#2a5e0c", 300: "#3d8a1c", 400: "#3d8a1c", 500: "#2a5e0c",
           600: "#1f4704", 700: "#1f4704", 800: "#163300", 900: "#0b1a02", 950: "#050d01"}
TEXT_A = {50: 1, 100: 1, 200: .94, 300: .86, 400: .7, 500: .58, 600: .46, 700: .36, 800: .3, 900: .24, 950: .2}
LINE_A = {50: .3, 100: .3, 200: .3, 300: .3, 400: .3, 500: .26, 600: .2, 700: .14, 800: .1, 900: .08, 950: .06}
MIST = (226, 246, 213)

pat = re.compile(r'dark:((?:hover|focus|group-hover|placeholder|disabled):)?(bg|text|border|divide|ring|from|to|via)-(gray|slate|zinc|neutral|stone)-(\d+)(?:/(\d+))?')
found = set()
for f in (ROOT / "src/app").rglob("*"):
    if f.suffix in (".html", ".ts", ".scss"):
        for m in pat.finditer(f.read_text(errors="ignore")):
            found.add(m.groups())

def hex2rgb(h):
    h = h.lstrip("#"); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def esc(s):
    return s.replace(":", "\\:").replace("/", "\\/")

out = [open(__file__).read().split('"""')[1].strip().join(["/*\n", "\n*/\n"]), "/* Generated by scripts/generate-wise-dark.py — do not edit by hand. */\n"]
for state, util, fam, shade, alpha in sorted(found, key=lambda t: (t[1], t[2], int(t[3]), t[0] or "", t[4] or "")):
    shade = int(shade)
    if shade not in SURFACE:
        continue
    a = int(alpha) / 100 if alpha else 1
    cls = f"dark:{state or ''}{util}-{fam}-{shade}" + (f"/{alpha}" if alpha else "")
    sel = "." + esc(cls)
    pseudo = ""
    pre = "body.dark "
    if state == "hover:": pseudo = ":hover"
    elif state == "focus:": pseudo = ":focus"
    elif state == "disabled:": pseudo = ":disabled"
    elif state == "group-hover:": pre = "body.dark .group:hover "
    elif state == "placeholder:": pseudo = "::placeholder"
    if util == "bg":
        r, g, b = hex2rgb(SURFACE[shade]); decl = f"background-color: rgba({r}, {g}, {b}, {a:g}) !important;"
    elif util == "text":
        decl = f"color: rgba({MIST[0]}, {MIST[1]}, {MIST[2]}, {TEXT_A[shade] * a:.3g}) !important;"
    elif util in ("border",):
        decl = f"border-color: rgba({MIST[0]}, {MIST[1]}, {MIST[2]}, {LINE_A[shade] * a:.3g}) !important;"
    elif util == "divide":
        sel += " > :not([hidden]) ~ :not([hidden])"
        decl = f"border-color: rgba({MIST[0]}, {MIST[1]}, {MIST[2]}, {LINE_A[shade] * a:.3g}) !important;"
    elif util == "ring":
        decl = f"--tw-ring-color: rgba({MIST[0]}, {MIST[1]}, {MIST[2]}, {LINE_A[shade] * a:.3g}) !important;"
    else:  # gradient stops: flatten to surface
        r, g, b = hex2rgb(SURFACE[shade])
        var = {"from": "--tw-gradient-from", "to": "--tw-gradient-to", "via": "--tw-gradient-via"}[util]
        decl = f"{var}: rgba({r}, {g}, {b}, {a:g}) !important;"
    out.append(f"{pre}{sel}{pseudo} {{ {decl} }}")
(ROOT / "src/styles/wise-dark.scss").write_text("\n".join(out) + "\n")
print(len(out) - 2, "rules")
